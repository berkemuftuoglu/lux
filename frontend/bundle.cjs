#!/usr/bin/env node
// Bundles the SvelteKit static build into files that Zig can @embedFile.
// Copies build output to ../src/static/ with a structure web.zig can serve.

const fs = require('fs');
const path = require('path');

const BUILD = path.join(__dirname, 'build');
const OUT = path.join(__dirname, '..', 'src', 'static');

// Clean old static output
if (fs.existsSync(OUT)) {
	fs.rmSync(OUT, { recursive: true });
}
fs.mkdirSync(OUT, { recursive: true });

// Copy index.html — rewrite asset paths to be root-relative
let html = fs.readFileSync(path.join(BUILD, 'index.html'), 'utf-8');
fs.writeFileSync(path.join(OUT, 'index.html'), html);

// Recursively copy _app/ directory
function copyDir(src, dest) {
	fs.mkdirSync(dest, { recursive: true });
	for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
		const srcPath = path.join(src, entry.name);
		const destPath = path.join(dest, entry.name);
		if (entry.isDirectory()) {
			copyDir(srcPath, destPath);
		} else {
			fs.copyFileSync(srcPath, destPath);
		}
	}
}

copyDir(path.join(BUILD, '_app'), path.join(OUT, '_app'));

// Generate a Zig file with @embedFile entries for all static files
const files = [];
function walk(dir, prefix) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const fullPath = path.join(dir, entry.name);
		const urlPath = prefix + '/' + entry.name;
		if (entry.isDirectory()) {
			walk(fullPath, urlPath);
		} else {
			const ext = path.extname(entry.name).toLowerCase();
			let contentType = 'application/octet-stream';
			if (ext === '.js') contentType = 'application/javascript';
			else if (ext === '.css') contentType = 'text/css';
			else if (ext === '.html') contentType = 'text/html';
			else if (ext === '.json') contentType = 'application/json';
			else if (ext === '.txt') contentType = 'text/plain';
			else if (ext === '.svg') contentType = 'image/svg+xml';
			else if (ext === '.png') contentType = 'image/png';
			else if (ext === '.ico') contentType = 'image/x-icon';

			// Relative path from src/ to static/
			const embedPath = path.relative(path.join(OUT, '..'), fullPath).replace(/\\/g, '/');
			files.push({ urlPath, contentType, embedPath, diskPath: 'src/' + embedPath });
		}
	}
}

// Walk _app directory
walk(path.join(OUT, '_app'), '/_app');

// Generate the Zig static_files tuple
let zig = '// Auto-generated by frontend/bundle.js — do not edit\n';
zig += '// Run: cd frontend && npm run build && node bundle.js\n\n';
zig += 'pub const static_files = .{\n';
for (const f of files) {
	zig += `    .{ "${f.urlPath}", "${f.contentType}", "${f.diskPath}", @embedFile("${f.embedPath}") },\n`;
}
zig += '};\n';

fs.writeFileSync(path.join(OUT, '..', 'static_files.zig'), zig);

console.log(`Bundled ${files.length} files to src/static/`);
console.log(`Generated src/static_files.zig`);
